function Format-OP2FilterCell {
    # A Markdown table cell: pipes escaped, code spans for patterns.
    param([string[]]$Text, [switch]$Code)
    $cells = @($Text | Where-Object { $_ } | ForEach-Object {
        $value = $_ -replace '\|', '\|'
        if ($Code) { '`' + $value + '`' } else { $value }
    })
    return ($cells -join ', ')
}

function ConvertTo-OPumper2FilterCatalogue {
    # The catalogue page of a module: one row per filter with its routes, what it delivers and the format its expressions
    # follow. Each catalogue module's doc/CATALOGUE.md is this output for its filters; a test keeps the two equal.
    [CmdletBinding()]
    [OutputType([string])]
    param([Parameter(Mandatory)][object[]]$Definition)
    $routes = @($Definition | ForEach-Object Routes).Count
    $lines = [Collections.Generic.List[string]]::new()
    $lines.Add('# Filter catalogue')
    $lines.Add('')
    $lines.Add("Generated by ``ConvertTo-OPumper2FilterCatalogue``: $($Definition.Count) filters, $routes routes. A route that another contributor registered first (``git status``, ``dotnet build``...) keeps that contributor's contract.")
    $lines.Add('')
    $lines.Add('| Filter | Routes | Delivers | Sections | Expressions follow |')
    $lines.Add('| --- | --- | --- | --- | --- |')
    foreach ($entry in @($Definition | Sort-Object Id)) {
        $sections = @(@($entry.Counters.Keys) + @($entry.Captures.Keys) + @($entry.Groups.Keys) + @($(if ($entry.Keep.Count) { 'Kept' })))
        $lines.Add("| ``$($entry.Id)`` | $(Format-OP2FilterCell $entry.Routes -Code) | $(Format-OP2FilterCell $entry.Description) | $(Format-OP2FilterCell $sections) | $(Format-OP2FilterCell $entry.Source) |")
    }
    return ($lines -join "`n") + "`n"
}
